def normalize_asr_timestamps(words, duration):
    """Keep raw hypotheses while exposing bounded repairs and unusable word timings."""
    result, anomalies, unaligned = [], [], []
    previous_end = 0.0
    for index, original in enumerate(words):
        word = dict(original)
        start, end = word.get("start"), word.get("end")
        if (isinstance(start, bool) or isinstance(end, bool) or
                not isinstance(start, (int, float)) or not isinstance(end, (int, float)) or
                not math.isfinite(start) or not math.isfinite(end) or end <= start):
            anomalies.append({"index": index, "reason": "invalid_or_nonfinite_timestamp"})
            unaligned.append({**word, "needs_review": True})
            continue
        repaired_start, repaired_end = max(0.0, previous_end, start), min(duration, end)
        if repaired_end <= repaired_start:
            anomalies.append({"index": index, "reason": "no_valid_nonoverlapping_interval"})
            unaligned.append({**word, "needs_review": True})
            continue
        if repaired_start != start or repaired_end != end:
            anomalies.append({"index": index, "reason": "bounded_temporal_repair",
                              "raw_start": start, "raw_end": end})
            word.update(raw_start=start, raw_end=end, timestamp_repaired=True)
        word.update(start=repaired_start, end=repaired_end)
        confidence = word.get("confidence")
        if (not isinstance(confidence, (int, float)) or isinstance(confidence, bool) or not math.isfinite(confidence)
            or not 0<=confidence<=1):
            word["raw_model_probability"] = confidence
            word["confidence"] = None
        result.append(word)
        previous_end = repaired_end
    return result, anomalies, unaligned


