def inspect_package(path: Path) -> dict:
    """Independently stream-check integrity, collisions, unsafe paths and strong secrets."""
    problems=[]
    seen=set()
    with zipfile.ZipFile(path) as archive:
        if archive.testzip():
            problems.append('zip_crc_failure')
        project='src/ldporto/pipeline.py' in archive.namelist()
        for entry in archive.infolist():
            name=entry.filename.replace('\\','/')
            normalized=name.casefold()
            if normalized in seen:
                problems.append('duplicate_or_windows_collision:'+name)
            seen.add(normalized)
            rel=Path(name)
            if name.startswith('/') or '..' in rel.parts or ':' in name:
                problems.append('unsafe_path:'+name)
            if project and any(part.casefold() in EXCLUDED_DIR_NAMES | {'.worker_v42','.venv311','.venv313'} for part in rel.parts):
                if not (rel.parts[0]=='models' and rel.name in MODEL_DOC_NAMES):
                    problems.append('forbidden_project_path:'+name)
            if project and (rel.suffix.casefold() in HEAVY_EXTENSIONS or sensitive_name(rel)):
                problems.append('forbidden_project_file:'+name)
            if entry.is_dir():
                continue
            carry=b''
            with archive.open(entry) as handle:
                for chunk in iter(lambda:handle.read(1024 * 1024),b''):
                    data=carry+chunk
                    if contains_strong_secret(data):
                        problems.append('strong_secret:'+name)
                        break
                    carry=data[-1024:]
        count=len(archive.infolist())
    return {'status':'PASS' if not problems else 'FAIL','entry_count':count,'issues':problems,
            'secret_scan':'all_uncompressed_entries_streamed','sha256':sha256_file(path)}


