def merge(base, extra, path=""):
    result = deepcopy(base)
    if not isinstance(extra, dict):
        raise ValueError("Configuração deve ser um objeto YAML.")
    if path == "understanding.":
        extra = deepcopy(extra)
        aliases = {"candidate_min_seconds": "hard_min_seconds", "candidate_preferred_min_seconds": "target_min_seconds",
                   "candidate_preferred_max_seconds": "target_max_seconds", "candidate_hard_max_seconds": "hard_max_seconds"}
        for old, new in aliases.items():
            if old in extra and new not in extra:
                extra[new] = extra[old]
    for key, value in extra.items():
        if key not in base:
            raise ValueError(f"Opção desconhecida: {path}{key}")
        if isinstance(base[key], dict):
            result[key] = merge(base[key], value, f"{path}{key}.")
        else:
            result[key] = value
    return result


def load_config(path=None):
    cfg = deepcopy(DEFAULTS)
    if path:
        cfg = merge(cfg, yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {})
    validate(cfg)
    return cfg


