def write_srt(path, captions):
    blocks = []
    for i, c in enumerate(captions):
        text = "\n".join(textwrap.wrap(c["text"], width=32, break_long_words=False,
                                      break_on_hyphens=False))
        blocks.append(f"{i+1}\n{stamp(c['start'], True)} --> {stamp(c['end'], True)}\n{text}")
    Path(path).write_text("\n\n".join(blocks)+("\n" if blocks else ""), encoding="utf-8")


