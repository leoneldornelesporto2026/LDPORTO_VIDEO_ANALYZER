def cuda_library_status():
    """Load required NVIDIA DLLs without inference; report actual loader failures."""
    if os.name!='nt':
        return {'checked':False,'status':'not_applicable','libraries':{}}
    import ctypes
    libraries={}
    for name in ('cublas64_12.dll','cudnn64_9.dll','cudart64_12.dll'):
        try:
            ctypes.WinDLL(name)
            libraries[name]={'loaded':True}
        except OSError:
            libraries[name]={'loaded':False}
    return {'checked':True,'status':'available' if all(item['loaded'] for item in libraries.values()) else 'missing',
            'libraries':libraries,'inference_executed':False}


def ctranslate2_cuda_info() -> Dict[str, object]:
    runtime = configure_windows_nvidia_runtime()
    result: Dict[str, object] = {"runtime": runtime, "device_count": None, "supported_compute_types": [],"import_succeeds":False}
    result['dll_status']=cuda_library_status()
    try:
        import ctranslate2
        result['import_succeeds']=True
        result["device_count"] = ctranslate2.get_cuda_device_count()
        try:
            result["supported_compute_types"] = sorted(ctranslate2.get_supported_compute_types("cuda"))
        except Exception as exc:
            result["compute_types_error"] = scrub(f"{type(exc).__name__}: {exc}")
    except Exception as exc:
        result["error"] = scrub(f"{type(exc).__name__}: {exc}")
    return result
