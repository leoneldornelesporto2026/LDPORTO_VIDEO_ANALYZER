def configure_local_mode(cfg):
    os.environ.setdefault("PYANNOTE_METRICS_ENABLED", "0")
    os.environ.setdefault("HF_HUB_DISABLE_TELEMETRY", "1")
    os.environ.setdefault("HF_HUB_DISABLE_SYMLINKS_WARNING", "1")
    os.environ.setdefault("DO_NOT_TRACK", "1")
    tools = cfg.get('media_tools', {})
    for key, environment in (('ffmpeg_path', 'LDPORTO_FFMPEG'), ('ffprobe_path', 'LDPORTO_FFPROBE'), ('ffmpeg_shared_dir', 'LDPORTO_FFMPEG_SHARED')):
        if tools.get(key):
            os.environ[environment] = str(asset_path(tools[key]))
    from .media_runtime import bootstrap_ffmpeg_shared
    bootstrap_ffmpeg_shared(tools.get('ffmpeg_shared_dir'))
    if cfg["offline"]:
        os.environ["HF_HUB_OFFLINE"] = "1"
        os.environ["TRANSFORMERS_OFFLINE"] = "1"
