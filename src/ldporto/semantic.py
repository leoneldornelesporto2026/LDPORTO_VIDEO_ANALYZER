def chunks(segments, seconds, max_chars):
    groups, current, size = [], [], 0
    for s in segments:
        cost = len(s["text"]) + 150
        if current and (s["end"]-current[0]["start"] > seconds or size+cost > max_chars):
            groups.append(current)
            current, size = [], 0
        current.append(s)
        size += cost
    if current:
        groups.append(current)
    return groups


def inferred_labels(text):
    t = normalized(text)
    categories, evidence = [], []
    rules = [
        ("strong_opinion", r"\b(nunca|jamais|com certeza|sem duvida|eu acho|na minha opiniao)\b"),
        ("emotion", r"\b(saudade|saudades|chorei|chorar|meu filho|minha filha|minha mae|meu pai|morreu)\b"),
        ("curiosity", r"\b(sabia|segredo|ninguem sabe|incrivel|imagine|imagina)\b"),
        ("conclusion", r"\b(portanto|por isso|no fim|no final|resumindo|enfim)\b"),
        ("call_to_action", r"\b(inscreva|se inscreve|segue|seguir|compartilha)\b"),
    ]
    for category, pattern in rules:
        match = re.search(pattern, t)
        if match:
            categories.append(category)
            evidence.append({"category": category, "lexical_match": match.group(0)})
    question = classify_question(text)
    if question['answer_expected']:
        categories.append('question')
        evidence.append({'category': 'question', 'question_type': question['question_type']})
    # No humor or controversy from a generic keyword: absence of evidence is null.
    return categories, evidence


def heuristic(group, index):
    text = " ".join(s["text"] for s in group)
    terms = [t for t in re.findall(r"\w+", normalized(text)) if len(t) > 3 and t not in STOPWORDS]
    keywords = [w for w, _ in Counter(terms).most_common(5)]
    tid = f"TOPIC_{index:05}"
    topic = {"topic_id": tid, "start": group[0]["start"], "end": group[-1]["end"],
             "topic": " / ".join(keywords) or "Fala sem rótulo confiável",
             "keywords": keywords, "summary": None,
             "evidence_segment_ids": [s["segment_id"] for s in group],
             "speakers": sorted({s["speaker"] for s in group if s.get("speaker")}),
             "people": [], "context_required": None,
             "method": "temporal_windows_and_keywords",
             "semantic_topic_change": None, "inference": True, "confidence": None}
    moments = []
    for s in group:
        labels, evidence = inferred_labels(s["text"])
        if not labels:
            continue
        moments.append({"moment_id": f"MOMENT_{index:05}_{len(moments):04}",
                        "start": s["start"], "end": s["end"],
                        "evidence_segment_ids": [s["segment_id"]], "text": s["text"],
                        "categories": labels, "reason": "Sinal lexical; requer avaliação humana.",
                        "lexical_evidence": evidence,
                        "editorial": {key: None for key in METRICS},
                        "standalone_class": "needs_context", "context_required": None,
                        "possible_start": s["start"], "possible_end": s["end"],
                        "complete_sentence": s["text"].rstrip().endswith((".", "?", "!")),
                        "method": "lexical_heuristic", "inference": True,
                        "confidence": None})
    return {"topics": [topic], "moments": moments}


def ollama_schema():
    source_ids = {"type": "array", "items": {"type": "string"}, "minItems": 1}
    metrics = {"type": "object",
               "properties": {key: {"type": ["number", "null"], "minimum": 0, "maximum": 1}
                              for key in METRICS},
               "required": METRICS, "additionalProperties": False}
    topic = {"type": "object", "properties": {
        "topic": {"type": "string"}, "summary": {"type": "string"},
        "segment_ids": source_ids, "context_required": {"type": "string", "enum": list(CONTEXT_REQUIREMENTS)}},
        "required": ["topic", "summary", "segment_ids", "context_required"],
        "additionalProperties": False}
    moment = {"type": "object", "properties": {
        "segment_ids": source_ids,
        "categories": {"type": "array", "items": {"type": "string", "enum": CATEGORIES}},
        "reason": {"type": "string"},
        "standalone_class": {"type": "string", "enum": STANDALONE},
        "context_required": {"type": "string", "enum": list(CONTEXT_REQUIREMENTS)}, "editorial": metrics},
        "required": ["segment_ids", "categories", "reason", "standalone_class",
                     "context_required", "editorial"], "additionalProperties": False}
    return {"type": "object", "properties": {
        "locale": {"type": "string", "enum": ["pt-BR"]},
        "topics": {"type": "array", "items": topic},
        "moments": {"type": "array", "items": moment}},
        "required": ["locale", "topics", "moments"], "additionalProperties": False}


