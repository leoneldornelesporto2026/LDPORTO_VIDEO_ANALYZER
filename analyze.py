def doctor(cfg):
    """Use the same enabled-capability readiness gate as an actual analysis."""
    import platform
    from ldporto.preflight import run_preflight
    from ldporto.core import versions, sanitize_json_numbers
    report = run_preflight(cfg)
    disk = shutil.disk_usage(ROOT)
    report.update(os=platform.platform(), architecture=platform.machine(), dependencies=versions(),
                  disk={"free_bytes": disk.free, "total_bytes": disk.total},
                  base_ready=report["ready"], ffmpeg=shutil.which("ffmpeg"), ffprobe=shutil.which("ffprobe"),
                  hf_token_configured=bool(os.environ.get("HF_TOKEN") or os.environ.get("HUGGING_FACE_HUB_TOKEN")),
                  notes=["Python 3.11.x e Windows 10/11 continuam sendo o alvo de homologacao.",
                         "runtime_target_match=false nao valida nem reprova a compatibilidade com Python 3.11.",
                         "Recursos habilitados indisponiveis nao sao rebaixados silenciosamente."])
    print(json.dumps(sanitize_json_numbers(report), ensure_ascii=False, indent=2, allow_nan=False))
    return 0 if report["ready"] else 2


