def transcription_metrics(data, duration):
    """Summarize observed review/timing quality; coverage is word-timing coverage."""
    words = data.get("words", [])
    alternatives = data.get("transcription_alternatives", [])
    low = [word for word in words if word.get('confidence') is None or word['confidence']<data.get('low_confidence_threshold',.6)]
    return {"word_count": len(words), "low_confidence_word_count": len(low),
            "low_confidence_word_fraction": len(low) / len(words) if words else None,
            "reviewed_region_count": len(alternatives),
            "auto_replacement_count": sum(bool(row.get("replacement_applied")) for row in alternatives),
            "unresolved_review_count": sum(bool(row.get("needs_review")) for row in words),
            "timestamp_anomaly_count": len(data.get("timestamp_anomalies", [])),
            "suspected_hallucination_region_count": len(data.get('suspected_hallucination_regions',[])),
            "unresolved_review_region_count":sum(bool(row.get('needs_human_review')) for row in alternatives),
            "review_needed_word_count":sum(bool(word.get('needs_review')) for word in words),
            "music_noise_evidence":'not_measured_when_audio_events_disabled',
            "speech_coverage": sum(word["end"] - word["start"] for word in words) / duration if duration > 0 else None,
            "coverage_method": "nonoverlapping_word_timing_not_vad_ground_truth"}
