#!/usr/bin/env python3
import argparse
import importlib.util
import json
import os
from pathlib import Path
import shutil
import sys

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT/"src"))


def configure_path():
    local_ffmpeg = ROOT/"tools"/"ffmpeg"/"bin"
    if local_ffmpeg.is_dir():
        os.environ["PATH"] = str(local_ffmpeg)+os.pathsep+os.environ.get("PATH", "")
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    # Register NVIDIA DLL folders from pip wheels before importing CTranslate2.
    try:
        from ldporto.gpu_runtime import configure_windows_nvidia_runtime
        configure_windows_nvidia_runtime()
    except Exception:
        pass


