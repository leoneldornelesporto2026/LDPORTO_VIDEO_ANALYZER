def write_zip_atomic(
    output: Path,
    files: Iterable[tuple[Path, str, str]],
    package_type: str,
    root_for_manifest: Path,
    max_file_mb: int,
    max_total_mb: int,
    extra_manifest: dict,
    readme_text: str,
    manifest_name: str,
    tree_name: str,
    readme_name: str,
) -> tuple[Path, dict]:
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".part")
    temporary.unlink(missing_ok=True)

    max_file_bytes = max_file_mb * 1024**2
    max_total_bytes = max_total_mb * 1024**2
    used = 0
    records: list[Record] = []
    skipped: list[dict] = []
    # Generated by GitHub Copilot - Oct-05-2026
    seen_names={name.casefold() for name in (manifest_name,tree_name,readme_name)}

    try:
        with zipfile.ZipFile(temporary, "x", zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
            for path, arcname, kind in files:
                if path.resolve() == output.resolve() or path.resolve() == temporary.resolve():
                    continue
                normalized=arcname.replace('\\','/')
                if normalized.startswith('/') or '..' in Path(normalized).parts or ':' in normalized:
                    raise ValueError('Caminho inseguro no pacote: '+normalized)
                if normalized.casefold() in seen_names:
                    raise ValueError('Entrada duplicada ou colisao Windows no ZIP: '+normalized)
                seen_names.add(normalized.casefold())
                arcname=normalized
                remaining = max_total_bytes - used
                data, problem = prepare_file(
                    path, arcname, kind, max_file_bytes, remaining, scan_secrets=True
                )
                if problem:
                    skipped.append(problem)
                    continue
                assert data is not None
                zf.writestr(arcname, data)
                used += len(data)
                records.append(
                    Record(
                        path=arcname,
                        bytes=len(data),
                        sha256=sha256_bytes(data),
                        kind=kind,
                        original_bytes=len(data),source_artifact=path.name,
                        compact_equivalent=COMPACT_EQUIVALENTS.get(path.name),
                    )
                )

            included_paths = sorted(r.path for r in records)
            tree = "\n".join(included_paths) + ("\n" if included_paths else "")
            manifest = {
                "package_type": package_type,
                "created_at_local": datetime.now().astimezone().isoformat(),
                "packager_python": sys.version.split()[0],
                "source_root": str(root_for_manifest),
                "included_file_count": len(records),
                "included_bytes": used,
                "included_human": human_size(used),
                "files": [asdict(r) for r in records],
                "skipped": skipped,
                "security_note": (
                    "Nomes sensiveis e padroes fortes de token/chave sao excluidos automaticamente. "
                    "A verificacao e heuristica; revise o manifesto antes de compartilhar."
                ),
                **extra_manifest,
                **export_readiness(package_type,root_for_manifest,records,skipped,extra_manifest),
            }
            zf.writestr(manifest_name, json.dumps(manifest, ensure_ascii=False, indent=2))
            zf.writestr(tree_name, tree)
            zf.writestr(readme_name, readme_text.strip() + "\n")

        # Integridade do container + hashes de todos os arquivos de origem inseridos.
        with zipfile.ZipFile(temporary, "r") as zf:
            bad = zf.testzip()
            if bad:
                raise ValueError(f"Falha de integridade no ZIP: {bad}")
            names = zf.namelist()
            duplicates = [name for name, count in Counter(names).items() if count > 1]
            if duplicates:
                raise ValueError("Entradas duplicadas no ZIP: " + ", ".join(duplicates))
            for record in records:
                if sha256_bytes(zf.read(record.path)) != record.sha256:
                    raise ValueError(f"Hash divergente dentro do ZIP: {record.path}")

        temporary.replace(output)
        return output, manifest
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


