def alternative_evidence(hypothesis, start, end):
    """Compare observable ASR proxies without treating model probability as truth."""
    words = hypothesis.get("words", [])
    probabilities = [word.get("confidence") for word in words
                     if isinstance(word.get("confidence"), (int, float)) and math.isfinite(word["confidence"])]
    valid = all(isinstance(word.get("start"), (int, float)) and isinstance(word.get("end"), (int, float)) and
                math.isfinite(word["start"] + word["end"]) and start <= word["start"] < word["end"] <= end
                for word in words)
    return {"word_count": len(words), "mean_model_probability": statistics.mean(probabilities) if probabilities else None,
            "timestamps_contained": valid, "calibrated_correctness_probability": False,
            "independent_audio_verification": False, "replacement_permitted": False}


