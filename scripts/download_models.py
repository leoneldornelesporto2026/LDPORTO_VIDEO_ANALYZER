def main():
    """Download official models atomically and require the source-package trusted hashes."""
    folder = ROOT/"models"
    folder.mkdir(exist_ok=True)
    manifest = {}
    for name, (url, min_size) in ASSETS.items():
        path = folder/name
        if not path.is_file() or path.stat().st_size < min_size or checksum(path)!=EXPECTED_SHA256[name]:
            print("Baixando "+name+"…", flush=True)
            temporary = path.with_suffix(path.suffix+".part")
            temporary.unlink(missing_ok=True)
            request = urllib.request.Request(url, headers={"User-Agent": "LDPortoAnalyzer/1.0"})
            try:
                with urllib.request.urlopen(request, timeout=60) as response, temporary.open("wb") as handle:
                    total=0
                    while block := response.read(1024*1024):
                        total+=len(block)
                        if total>100*1024**2:
                            raise ValueError('Asset excede limite esperado.')
                        handle.write(block)
                if temporary.stat().st_size < min_size or checksum(temporary)!=EXPECTED_SHA256[name]:
                    raise ValueError('Hash de modelo diverge do manifesto confiavel; asset nao instalado.')
                temporary.replace(path)
            finally:
                temporary.unlink(missing_ok=True)
        h = hashlib.sha256()
        with path.open("rb") as f:
            while block := f.read(1024*1024):
                h.update(block)
        manifest[name] = {"url": url, "sha256": h.hexdigest(), "size": path.stat().st_size}
    temporary=folder/'vision_models_manifest.json.tmp'
    temporary.write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    temporary.replace(folder/'vision_models_manifest.json')
    print("Modelos visuais disponíveis. Checksums locais registrados.")


