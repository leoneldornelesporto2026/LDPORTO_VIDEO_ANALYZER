def read_json(path: Path, max_bytes: int = 32 * 1024 ** 2):
    """Bound optional JSON inspection instead of loading monolithic legacy artifacts."""
    try:
        if path.stat().st_size>max_bytes:
            return None
        with path.open(encoding='utf-8-sig') as handle:
            return json.load(handle,parse_constant=lambda value: (_ for _ in ()).throw(ValueError('nonfinite JSON')))
    except Exception:
        return None


def referenced_images(analysis: Path, maximum: int) -> list[Path]:
    if maximum <= 0:
        return []

    source_names=["thumbnail_candidates.json","moment_frames.json","participants.json","people.json",
                  "second_curation_package.json","main_moments.json"]
    results: list[Path] = []
    seen: set[Path] = set()

    def add_candidate(raw: str) -> None:
        if len(results) >= maximum:
            return
        raw = raw.strip().replace("\\", "/")
        if not raw:
            return
        candidate = Path(raw)
        if not candidate.is_absolute():
            candidate = analysis / candidate
        try:
            candidate = candidate.resolve()
            candidate.relative_to(analysis.resolve())
        except (ValueError, OSError):
            return
        if (
            candidate.is_file()
            and not linked(candidate)
            and candidate.suffix.lower() in ANALYSIS_IMAGE_EXTENSIONS
            and candidate not in seen
        ):
            seen.add(candidate)
            results.append(candidate)

    def inspect(value) -> None:
        if len(results) >= maximum:
            return
        if isinstance(value, dict):
            for key, item in value.items():
                if (
                    isinstance(item, str)
                    and any(token in str(key).lower() for token in IMAGE_REFERENCE_KEYS)
                ):
                    add_candidate(item)
                inspect(item)
                if len(results) >= maximum:
                    return
        elif isinstance(value, list):
            for item in value:
                inspect(item)
                if len(results) >= maximum:
                    return

    for name in source_names:
        p = analysis / name
        if not p.is_file():
            continue
        data = read_json(p,max_bytes=8 * 1024 ** 2)
        if data is not None:
            inspect(data)
        if len(results) >= maximum:
            break

    return results


def collect_analysis_files(analysis: Path, include_images: bool, max_images: int) -> list[tuple[Path, str]]:
    selected: list[tuple[Path, str]] = []
    seen: set[Path] = set()

    def add(p: Path, kind: str) -> None:
        if not p.is_file() or linked(p) or analysis_path_excluded(p, analysis):
            return
        rp = p.resolve()
        if rp in seen:
            return
        if p.suffix.lower() in HEAVY_EXTENSIONS:
            return
        seen.add(rp)
        selected.append((p, kind))

    for name in ANALYSIS_PRIORITY_FILES:
        add(analysis / name, "priority")

    # Inclui novos contratos textuais que ainda nao existiam quando o script foi criado.
    for p in sorted(analysis.rglob("*"), key=lambda x: x.as_posix().lower()):
        if not p.is_file() or linked(p) or analysis_path_excluded(p, analysis):
            continue
        if p.suffix.lower() in ANALYSIS_TEXT_EXTENSIONS:
            add(p, "textual_evidence")

    if include_images:
        for p in referenced_images(analysis, max_images):
            add(p, "referenced_image")

    # Generated by GitHub Copilot - Oct-05-2026
    compact_names=set(COMPACT_EQUIVALENTS.values())
    essential_names=set(ANALYSIS_ESSENTIAL_FILES)-set(COMPACT_EQUIVALENTS)
    order={name:index for index,name in enumerate(ANALYSIS_PRIORITY_FILES)}
    return sorted(selected,key=lambda item:(
        0 if item[0].name in compact_names | essential_names else 1 if 'review_evidence' in item[0].relative_to(analysis).parts else 2,
        order.get(item[0].name,len(order)),item[0].relative_to(analysis).as_posix()))


def prepare_file(
    path: Path,
    rel: str,
    kind: str,
    max_file_bytes: int,
    remaining_bytes: int,
    scan_secrets: bool = True,
) -> tuple[bytes | None, dict | None]:
    try:
        size = path.stat().st_size
    except OSError as exc:
        return None, {"path": rel, "reason": "stat_error", "detail": str(exc)}

    if size > max_file_bytes:
        return None, {"path": rel, "reason": "file_too_large", "bytes": size, "original_bytes":size,
                      "sha256":sha256_file(path), "included":False, "source_artifact":path.name,
                      "compact_equivalent":COMPACT_EQUIVALENTS.get(path.name)}
    if size > remaining_bytes:
        return None, {"path": rel, "reason": "total_limit", "bytes": size, "original_bytes":size,
                  "sha256":sha256_file(path), "included":False, "source_artifact":path.name,
                  "compact_equivalent":COMPACT_EQUIVALENTS.get(path.name)}
    if sensitive_name(path):
        return None, {"path": rel, "reason": "sensitive_filename", "bytes": size}

    try:
        data = path.read_bytes()
    except OSError as exc:
        return None, {"path": rel, "reason": "read_error", "detail": str(exc)}

    if scan_secrets:
        if contains_strong_secret(data):
            return None, {"path": rel, "reason": "possible_secret_value", "bytes": size,
                          "original_bytes":size,"included":False,"source_artifact":path.name,
                          "compact_equivalent":None,"sha256":sha256_bytes(data)}

    return data, None


