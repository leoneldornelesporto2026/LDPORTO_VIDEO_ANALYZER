def test_director_cache_scoped_and_resume(tmp_path, monkeypatch):
    m, v, shots = fixture(12)
    cfg = load_config()
    logger = logging.getLogger('cache')
    ctx = Context(Path('absent video.mp4'), tmp_path, cfg, 'sha', logger)
    raw = [turn(0, 12)]
    d = run_director_stage(ctx, m, v, shots, raw, [], {}, {})
    key = ctx.states['19_camera_director']['key']
    import ldporto.director_integration as integration
    original = integration.build_camera_director
    monkeypatch.setattr(integration, 'build_camera_director', lambda *a, **kw: pytest.fail('Director cache missed'))
    ctx2 = Context(ctx.video, tmp_path, cfg, 'sha', logger)
    assert run_director_stage(ctx2, m, v, shots, raw, [], {}, {}) == d
    assert ctx2.states['19_camera_director']['key'] == key
    monkeypatch.setattr(integration, 'build_camera_director', original)
    cfg['camera_director']['profile'] = 'podcast'
    ctx3 = Context(ctx.video, tmp_path, cfg, 'sha', logger)
    run_director_stage(ctx3, m, v, shots, raw, [], {}, {})
    assert ctx3.states['19_camera_director']['key'] != key
    # Real change to input evidence invalidates Director independently of profile.
    previous = ctx3.states['19_camera_director']['key']
    raw[0]['confidence'] = .2
    ctx4 = Context(ctx.video, tmp_path, cfg, 'sha', logger)
    run_director_stage(ctx4, m, v, shots, raw, [], {}, {})
    assert ctx4.states['19_camera_director']['key'] != previous


def test_schemas_and_interval_invariants():
    m, v, shots = fixture(19.1, pair=True, distant=True, cuts=(5.3, 11.9))
    d = build_camera_director(m, v, shots, [turn(0, 19.1, overlap=True),turn(0, 19.1, 'PERSON_B', overlap=True)], [], {})['data']
    jsonschema.validate(d['timeline'], read_json(ROOT/'schemas/camera_director_timeline.schema.json'))
    jsonschema.validate(d['debug'], read_json(ROOT/'schemas/camera_director_debug.schema.json'))
    json.dumps(d, allow_nan=False)
    last = 0
    for r in d['timeline']:
        assert abs(r['start']-last) < 1e-7
        assert r['start'] < r['end'] <= m['duration']
        shot = next(s for s in shots if s['shot_id'] == r['source_shot_id'])
        assert shot['start'] <= r['start'] < r['end'] <= shot['end']
        assert r['focus_person'] is None or r['focus_person'] in r['visible_people']
        if r['split']:
            assert {r['split']['left_person'],r['split']['right_person']} <= set(r['visible_people'])
        last = r['end']
    assert last == m['duration']


