def safe_image_reference(value):
    """Allow only local relative report images; reject traversal and network references."""
    if not isinstance(value,str):
        return False
    normalized=value.replace('\\','/')
    parsed=urlsplit(normalized)
    path=PurePosixPath(normalized)
    return bool(normalized and not parsed.scheme and not parsed.netloc and not path.is_absolute() and
                '..' not in path.parts and ':' not in normalized and path.suffix.lower() in ('.jpg','.jpeg','.png','.webp'))


