    json.dumps(data, allow_nan=False)
    jsonschema.validate(data, global_review_schema())
    by_id = {candidate["moment_id"]: candidate for candidate in candidates}
    seen = set()
    metadata = [data["overview"], *data["notes"]]
    for row in data["top_moments"]:
        moment_id = row["moment_id"]
        if moment_id not in by_id or moment_id in seen:
            raise ValueError("Revisao global citou moment_id invalido ou duplicado.")
        seen.add(moment_id)
        candidate = by_id[moment_id]
        if not set(row["evidence_segment_ids"]) <= set(candidate.get("evidence_segment_ids", [])):
            raise ValueError("Justificativa mistura evidencia de outro momento.")
        excerpt = row.get("literal_excerpt")
        if excerpt and " ".join(excerpt.split()) not in " ".join(candidate.get("text", "").split()):
            raise ValueError("Citacao literal nao pertence ao momento informado.")
        metadata.extend(row[key] for key in ("why", "hook_text", "title_idea", "context_note"))
    for angle in data["content_angles"]:
        if any(moment_id not in by_id for moment_id in angle["moment_ids"]):
            raise ValueError("Revisao global citou moment_id inexistente em content_angles.")
        metadata.extend((angle["angle"], angle["reason"]))
    require_pt_br(metadata)
    return True


