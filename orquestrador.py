def timestamp() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')


def note(message: str) -> None:
    print(f'[{dt.datetime.now():%H:%M:%S}] {message}', flush=True)


def hash_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as source:
        for part in iter(lambda: source.read(1024 * 1024), b''):
            h.update(part)
    return h.hexdigest()


def write_json(path: Path, obj: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replace prevents half-written checkpoint state on interruption.
    temp = path.with_name(path.name + f'.{os.getpid()}.tmp')
    with temp.open('w', encoding='utf-8', newline='\n') as stream:
        json.dump(obj, stream, indent=2, ensure_ascii=False)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temp, path)


def load_json(path: Path):
    return json.loads(path.read_text(encoding='utf-8'))


def walk_source_files():
    for parent, dirs, files in os.walk(ROOT, followlinks=False):
        folder = Path(parent)
        rel_dir = folder.relative_to(ROOT)
        # Evidence and execution state are NEVER considered source code.
        if rel_dir == Path('automacao'):
            dirs[:] = [d for d in dirs if d not in {'execucao', 'evidencias'}]
        dirs[:] = [d for d in dirs if d not in EXCLUDED_DIRS and not (folder / d).is_symlink()]
        if rel_dir.parts and rel_dir.parts[0] == '.package':
            # Existing exporter metadata are not regenerated by the autopilot.
            pass
        for name in files:
            path = folder / name
            low = name.lower()
            if path.is_symlink() or path.suffix.lower() in EXCLUDED_EXT:
                continue
            if low in {'.env', 'credentials.json', 'secrets.json'} or low.startswith('.env.'):
                continue
            if any(re.fullmatch(pattern, low) for pattern in (r'credentials.*\.json', r'secrets.*\.json')):
                continue
            if path.stat().st_size > MAX_SOURCE_BYTES:
                continue
            yield path


def manifest() -> dict[str, str]:
    return {p.relative_to(ROOT).as_posix(): hash_file(p) for p in sorted(walk_source_files())}


def manifest_hash(index: dict[str, str]) -> str:
    raw = json.dumps(index, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()
    return hashlib.sha256(raw).hexdigest()


def snapshot(label: str) -> dict:
    SNAPSHOTS.mkdir(parents=True, exist_ok=True)
    name = re.sub(r'[^a-zA-Z0-9_-]', '_', label)
    target = SNAPSHOTS / f'{name}.zip'
    tmp = SNAPSHOTS / f'{name}.zip.part'
    with zipfile.ZipFile(tmp, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6, allowZip64=True) as archive:
        for path in sorted(walk_source_files()):
            archive.write(path, path.relative_to(ROOT).as_posix())
    with zipfile.ZipFile(tmp) as archive:
        bad = archive.testzip()
        if bad:
            tmp.unlink(missing_ok=True)
            raise RuntimeError(f'Snapshot com erro de CRC: {bad}')
    os.replace(tmp, target)
    return {'file': target.relative_to(ROOT).as_posix(), 'sha256': hash_file(target),
            'bytes': target.stat().st_size}


def load_plan() -> list[dict]:
    """Detecta ETAPA_XX.txt contíguos. MAPA_ETAPAS.json é opcional e só dá títulos.

    Não edita mapa, prompts nem checkpoints. Nunca pula numeração ou sobrescreve
    tarefas já concluídas. O número de etapas é decidido a cada execução.
    """
    if not PROMPTS.is_dir():
        raise RuntimeError('Pasta de prompts ausente: ' + str(PROMPTS))
    titles = {}
    if PLAN.exists():
        legacy = load_json(PLAN)
        if not isinstance(legacy, list):
            raise RuntimeError('MAPA_ETAPAS.json precisa ser uma lista.')
        for row in legacy:
            number = int(row['n'])
            target = (AUTO / str(row['file_path'])).resolve()
            if not target.is_relative_to(PROMPTS.resolve()) or target.name != f'ETAPA_{number:02d}.txt':
                raise RuntimeError(f'Mapa contém caminho inseguro ou não canônico: {row}')
            if number in titles:
                raise RuntimeError(f'Mapa duplicou etapa {number}.')
            titles[number] = str(row.get('title') or f'Etapa {number}')
    found = {}
    for file in PROMPTS.glob('ETAPA_*.txt'):
        match = re.fullmatch(r'ETAPA_([1-9][0-9]*)\.txt', file.name)
        # A etapa 01 até 09 tem zero à esquerda; 10+ mantêm nome canônico.
        if not match:
            match = re.fullmatch(r'ETAPA_(0[1-9])\.txt', file.name)
        if not match or file.is_symlink():
            raise RuntimeError(f'Nome de prompt inválido ou symlink: {file.name}')
        number = int(match.group(1))
        if file.name != f'ETAPA_{number:02d}.txt' or number in found:
            raise RuntimeError(f'Prompt duplicado/não canônico: {file.name}')
        if not file.is_file() or file.stat().st_size == 0:
            raise RuntimeError(f'Prompt ausente/vazio: {file.name}')
        found[number] = file
    if not found:
        raise RuntimeError('Nenhum prompt ETAPA_XX.txt encontrado.')
    numbers = sorted(found)
    if numbers != list(range(1, numbers[-1] + 1)):
        missing = sorted(set(range(1, numbers[-1] + 1)) - set(found))
        raise RuntimeError(f'Prompts fora de sequência; faltando: {missing[:12]}')
    if any(number not in found for number in titles):
        raise RuntimeError('O mapa legado referencia prompt ausente.')
    entries = []
    for number in numbers:
        title = titles.get(number)
        if title is None:
            first_lines = found[number].read_text(encoding='utf-8-sig').splitlines()[:3]
            first = next((line.strip() for line in first_lines if 'ETAPA' in line.upper()), '')
            found_title = re.search(r'ETAPA\s+\d+\s*/\s*\d+\s*[—–-]\s*([^\r\n]+)', first, re.I)
            title = found_title.group(1).strip()[:140] if found_title else f'Etapa {number:02d}'
        entries.append({'n': number, 'file_path': f'prompts/ETAPA_{number:02d}.txt', 'title': title})
    return entries


def total_steps() -> int:
    return len(load_plan())


def guard_hashes() -> dict:
    tracked = GUARD_FILES + sorted(PROMPTS.glob('ETAPA_*.txt'))
    return {p.relative_to(ROOT).as_posix(): hash_file(p) for p in tracked if p.exists()}


def verify_guard(expected: dict) -> None:
    if guard_hashes() != expected:
        raise RuntimeError('Codex alterou o próprio orquestrador, plano ou prompts. Etapa pausada para revisão.')


def read_state() -> dict | None:
    return load_json(STATE) if STATE.is_file() else None


def require_state() -> dict:
    state = read_state()
    if state is None:
        raise RuntimeError('Execute primeiro: python orquestrador.py --init')
    return state


def persist(state: dict) -> None:
    state['updated_at'] = timestamp()
    write_json(STATE, state)


@contextlib.contextmanager
def exclusive_lock():
    RUN.mkdir(parents=True, exist_ok=True)
    try:
        descriptor = os.open(str(LOCK), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError as exc:
        raise RuntimeError(f'Existe outra execução ou lock residual em {LOCK}. Não inicie processos simultâneos. Consulte o guia de recuperação.') from exc
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8') as stream:
            stream.write(json.dumps({'pid': os.getpid(), 'created_at': timestamp()}, ensure_ascii=False))
        yield
    finally:
        LOCK.unlink(missing_ok=True)


def setup() -> dict:
    load_plan()
    existing = read_state()
    if existing:
        note('Já inicializado: estado preservado. Não recriei baseline.')
        return existing
    if not (ROOT / 'src').is_dir() or not (ROOT / 'analyze.py').exists():
        raise RuntimeError('Coloque o orquestrador na RAIZ do Analyzer existente. Não crio nem substituo o projeto.')
    count, errors = syntax_check()
    if errors:
        raise RuntimeError('Base atual já tem erros Python 3.11: ' + '\n'.join(errors[:5]))
    with exclusive_lock():
        code, baseline_tests = run_pytest(0, 1200)
        if code != 0:
            raise RuntimeError('Regressão da baseline já falha; corrija antes de inicializar. Log: ' + baseline_tests)
        baseline = snapshot('ETAPA_00_BASELINE')
        current = manifest()
        evidences = {p.name: hash_file(p) for p in EVIDENCE.glob('*.zip')}
        state = {
            'schema_version': 2, 'created_at': timestamp(), 'updated_at': timestamp(),
            'completed': 0, 'active': None, 'status': 'READY', 'stages': [],
            'baseline_snapshot': baseline, 'last_snapshot': baseline,
            'last_manifest_sha256': manifest_hash(current),
            'last_manifest': current,
            'evidence_sha256': evidences, 'guard_hashes': guard_hashes(),
            'python_sources_checked': count, 'baseline_pytest_log': baseline_tests,
        }
        persist(state)
    note(f'Baseline preservada ({count} arquivos .py). Próximo: ETAPA 01.')
    return state


def syntax_check() -> tuple[int, list[str]]:
    count = 0
    errors = []
    for file in walk_source_files():
        if file.suffix.lower() != '.py':
            continue
        count += 1
        try:
            ast.parse(file.read_text(encoding='utf-8-sig'), filename=str(file), feature_version=(3, 11))
        except (SyntaxError, UnicodeError, ValueError) as exc:
            errors.append(f'{file.relative_to(ROOT)}: {exc}')
    return count, errors


def run_pytest(stage: int, timeout: int) -> tuple[int, str]:
    LOGS.mkdir(parents=True, exist_ok=True)
    log = LOGS / f'ETAPA_{stage:02d}_pytest.log'
    with log.open('w', encoding='utf-8', errors='replace') as output:
        try:
            completed = subprocess.run(
                [sys.executable, '-m', 'pytest', '-q'], cwd=ROOT,
                stdout=output, stderr=subprocess.STDOUT,
                timeout=timeout, check=False,
            )
            code = completed.returncode
        except subprocess.TimeoutExpired:
            output.write('\nTIMEOUT: regressão excedeu limite configurado.\n')
            code = 124
    return code, log.relative_to(ROOT).as_posix()


def find_codex() -> str | None:
    return shutil.which('codex') or shutil.which('codex.cmd')


def doctor() -> bool:
    problems = []
    note(f'Projeto: {ROOT}')
    note(f'Python: {sys.version.split()[0]} ({sys.executable})')
    if sys.version_info < (3, 11):
        problems.append('Python 3.11+ é obrigatório.')
    try:
        items = load_plan()
        note(f'Prompts: {len(items)}; primeiro: {items[0]["title"]}')
    except Exception as exc:
        problems.append(str(exc))
    for basename in ('SECOND_CURATION_READY.zip', 'CHATGPT_REVIEW.zip'):
        path = EVIDENCE / basename
        note(f'Evidência {basename}: {"presente" if path.is_file() else "ausente (opcional, não inventar)"}')
    cli = find_codex()
    if not cli:
        problems.append('Codex CLI não encontrado. Instale via npm e confirme codex --version.')
    else:
        try:
            r = subprocess.run([cli, '--version'], capture_output=True, text=True, timeout=20)
            note('Codex CLI: ' + (r.stdout.strip() or r.stderr.strip()))
            if r.returncode:
                problems.append('codex --version falhou.')
            auth = subprocess.run([cli, 'login', 'status'], capture_output=True, text=True, timeout=25)
            note('Codex login: ' + ('autenticado' if auth.returncode == 0 else 'não autenticado'))
            if auth.returncode:
                problems.append('Codex CLI sem login. Rode: codex login')
        except Exception as exc:
            problems.append(f'Codex CLI inacessível: {exc}')
    try:
        r = subprocess.run([sys.executable, '-m', 'pytest', '--version'], capture_output=True, text=True, timeout=20)
        note('pytest: ' + (r.stdout.strip() or r.stderr.strip()))
        if r.returncode:
            problems.append('pytest indisponível neste ambiente Python.')
    except Exception as exc:
        problems.append(f'pytest indisponível: {exc}')
    count, errors = syntax_check()
    note(f'AST Python 3.11: {count} arquivos, {len(errors)} erros.')
    problems.extend(errors[:5])
    note(f'Status: {"PRONTO PARA TESTE LOCAL" if not problems else "BLOQUEADO"}')
    for problem in problems:
        note(' - ' + problem)
    note('NOTA: doctor não consome tokens; não certifica franquia disponível nem execução no Windows.')
    return not problems


