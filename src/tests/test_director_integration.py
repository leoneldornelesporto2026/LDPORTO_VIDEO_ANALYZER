def test_preview_renderer_and_verifier_use_rendered_frames(tmp_path):
    from ldporto.preview_renderer import render_preview, select_canary_intervals
    from ldporto.preview_verifier import verify_preview
    video = tmp_path/'preview source.mp4'
    make_media(video)
    metadata = {"duration":4.0,"width":640,"height":360,"fps":10.0,"rotation":0}
    timeline = [{
        "schema_version":"3.0","director_id":"DIRECTOR_000000","start":0.0,"end":4.0,
        "layout":"full_frame","focus_person":None,"split":None,"focus_confidence":None,
        "camera":{"transition_in":"initial","keyframes":[
            {"time":0.0,"center":[.5,.5],"zoom":1.0,"velocity":[0,0,0]},
            {"time":4.0,"center":[.5,.5],"zoom":1.0,"velocity":[0,0,0]}]},
        "crop":{"rect_end":None}
    }]
    canaries = select_canary_intervals(timeline, 4.0, 2, 2.0)
    assert canaries
    out = tmp_path/'preview.mp4'
    rendered = render_preview(video,timeline,metadata,out,{"start":0.0,"end":2.0},180,320)
    assert rendered["status"] == "ok" and out.is_file()
    checked = verify_preview(out,{"width":180,"height":320,"duration":2.0},timeline)
    assert checked["data"]["verifier_uses_rendered_frames"] is True
    assert checked["data"]["output_dimensions"] == [180,320]
