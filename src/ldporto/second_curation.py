def _rows_in(rows, start, end):
    return [r for r in rows if overlap(start, end, r.get('start',0), r.get('end',0)) > 0]


def _text(words):
    parts=[]
    for w in words:
        token=w.get('word') or w.get('text') or ''
        if token:
            parts.append(token)
    return ' '.join(parts).replace(' ,', ',').replace(' .','.').replace(' ?','?').replace(' !','!').strip()


def _candidate_source(analysis):
    main=analysis.get('main_moments') or []
    if main:
        rows=[]
        for m in main:
            core=m.get('core_moment') or {}
            start=m.get('ideal_start', core.get('start', m.get('start',0)))
            end=m.get('ideal_end', core.get('end', m.get('end',start)))
            rows.append({**m, '_start': start, '_end': end})
        return rows
    return [{**m, '_start':m.get('possible_start',m.get('start',0)), '_end':m.get('possible_end',m.get('end',0))}
            for m in analysis.get('editorial_moments',[])]


