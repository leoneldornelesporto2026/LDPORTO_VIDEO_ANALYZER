def test_global_planner_is_deterministic_and_prefers_stay_put():
    from ldporto.global_camera_planner import build_global_camera_plan
    m, v, shots = fixture(12, pair=True)
    camera = []
    for i in range(12):
        camera.append({
            "start": float(i), "end": float(i+1), "shot_id": shots[0]["shot_id"],
            "shot_type": "two_shot", "active_person": "PERSON_A" if i < 6 else "PERSON_B",
            "active_person_confidence": .9, "visible_people": ["PERSON_A","PERSON_B"],
            "speech_overlap": False, "vertical_crop": {"recommended_layout":"single_person"}
        })
    cfg = load_config()["camera_director"]
    one = build_global_camera_plan(m, v, shots, camera, cfg)["data"]
    two = build_global_camera_plan(m, v, shots, camera, cfg)["data"]
    assert one == two
    assert one["selected_global_path"]
    assert one["metrics"]["expected_switches"] <= 3
    assert one["schema_version"] == "4.0"


