def _pre_score(moment):
    vals = [v for v in (moment.get("editorial") or {}).values() if isinstance(v, (int, float))]
    base = max(vals) if vals else 0.0
    cats = set(moment.get("categories") or [])
    bonus = 0.12 if cats & {"hook", "curiosity", "surprise", "strong_opinion", "emotion", "humor", "controversy"} else 0
    standalone = 0.10 if moment.get("standalone_class") == "excellent" else 0.05 if moment.get("standalone_class") == "good" else 0
    return min(1.0, base + bonus + standalone)


