def sha256_file(path: Path) -> str:
    """Checksum omitted large evidence with bounded memory rather than loading it."""
    checksum = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b''):
            checksum.update(block)
    return checksum.hexdigest()


def linked(path: Path) -> bool:
    try:
        attrs = getattr(path.lstat(), "st_file_attributes", 0)
    except OSError:
        attrs = 0
    return path.is_symlink() or (
        hasattr(path, "is_junction") and path.is_junction()
    ) or bool(attrs & 0x400)


def sensitive_name(path: Path) -> bool:
    name = path.name.lower()
    if name in SENSITIVE_EXACT_NAMES or name.startswith(".env."):
        return True
    if path.suffix.lower() in SENSITIVE_KEY_EXTENSIONS:
        return True
    return bool(SENSITIVE_FILENAME_RE.search(path.name))


def contains_strong_secret(data: bytes) -> bool:
    # Evita escanear binarios gigantes; os binarios de qualquer forma nao entram.
    return any(pattern.search(data) for pattern in STRONG_SECRET_PATTERNS)


def is_generated_package_name(name: str) -> bool:
    upper = name.upper()
    if name.casefold() in {derived.casefold() for derived in DERIVED_PACKAGE_NAMES} or name in WORKER_TEMP_FILES:
        return True
