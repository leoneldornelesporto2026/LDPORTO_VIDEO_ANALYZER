def test_dynamic_sampling_changes_without_second_pass():
    scheduler = SamplingScheduler(load_config()['vision'])
    fast, why = scheduler.frequency(0, speaking=True, speaker='A', boundary=True, motion=0, visible_count=1, mouth_count=1)
    stable, why = scheduler.frequency(3, speaking=True, speaker='A', boundary=False, motion=0, visible_count=1, mouth_count=1)
    motion, why = scheduler.frequency(4, speaking=True, speaker='A', boundary=False, motion=.2, visible_count=1, mouth_count=1)
    assert fast > stable and motion == fast
    assert 'high_motion' in why


def test_real_legacy_sample_can_be_read_without_inventing_evidence():
    sample = ROOT/'src/tests/fixtures/legacy_analysis'
    insights = read_json(sample/'llm_insights.json')
    words = read_json(sample/'words.json')
    legacy = read_json(sample/'timeline.json')
    # Use only timestamps/boxes actually included in the legacy sample.
    frames, observations = {}, {}
    for r in legacy:
        t = r.get('visual_observed_at')
        if t is None:
            continue
        frames[t] = {'time': t, 'scene_id': r.get('scene_id'), 'visible_people': r['visible_people']}
        for o in r.get('people_positions', []):
            observations[(t, o['person_id'])] = {**o,'time': t,'scene_id': r.get('scene_id'),
                                                 'face_visible': bool(o.get('face_bbox'))}
    scenes = read_json(sample/'scenes.json')
    shots = [{**s, 'shot_id': 'LEGACY_'+s['scene_id'], 'shot_type': s.get('scene_type','unknown')} for s in scenes]
    v = {'frames': list(frames.values()), 'observations': list(observations.values())}
    d = build_camera_director(insights['video'],v,shots,[],[],{},insights.get('questions_answers',[]))
    assert words and len(legacy) > 0
    assert not read_json(sample/'speakers.json')
    assert not any(r['focus_person'] for r in d['data']['timeline'])
    assert not any(r['split'] for r in d['data']['timeline'])
    assert d['status'] in ('partial','unavailable')
    json.dumps(d, allow_nan=False)


